AndroidTrait = AndroidTrait or {}

function AndroidTrait.toggleNVG()
	local pl = getPlayer()
	pl:setWearingNightVisionGoggles(not pl:isWearingNightVisionGoggles())
end

function AndroidTrait.dbgAndroid()
	local pl = getPlayer()
	AndroidTrait.initTrait()
	if AndroidTrait.hasTrait(pl) then
		AndroidTrait.setTrait(pl, false)
	else
		AndroidTrait.setTrait(pl, true)
	end

	local msg = "Android: "..tostring(AndroidTrait.hasTrait(pl))
	print(tostring(msg))
	pl:setHaloNote(tostring(msg),150,250,150,235)
end

function AndroidTrait.recharge(battery)
	if not battery then return end
	local pl = getPlayer()
	local usedDelta = AndroidTrait.getBatteryCharge(battery)
	print("usedDelta: "..tostring(usedDelta))
	local chargeGained = usedDelta
	AndroidTrait.applyEnergy(pl, chargeGained)
	local container = battery:getContainer()
	if container then container:Remove(battery) end
	HaloTextHelper.addTextWithArrow(pl, "Energy: " .. tostring(AndroidTrait.getEnergyPercent()), true, 0, 0, 255)
	local sq = pl:getSquare()
	if isClient() and sq then
		getSoundManager():PlayWorldSound('Android_Charge', sq, 0, 5, 5, false)
	else
		getSoundManager():playUISound("Android_Charge")
	end
	AndroidTrait.doAnim(ZombRand(1, 10))
end

function AndroidTrait.getEnergyPercent()
	local pl = getPlayer()
	local energy = pl:getModData()['AndroidTraitData']["Energy"]
    return math.floor(energy * 100 + 0.5)
end
