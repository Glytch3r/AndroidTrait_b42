AndroidTrait = AndroidTrait or {}

function AndroidTrait.energyHandler(pl)
	if not pl then pl = getPlayer() end
	if not pl or not AndroidTrait.hasTrait(pl) then
		return
	end
	local stats = pl:getStats()
	local bd = pl:getBodyDamage()
	local md = pl:getModData()
	if not md['AndroidTraitData'] then return end
	local energy = md['AndroidTraitData']["Energy"] or 0
	local drunk = stats:get(CharacterStat.INTOXICATION)
	local hunger = stats:get(CharacterStat.HUNGER)
	local thirst = stats:get(CharacterStat.THIRST)
	local fatigue = stats:get(CharacterStat.FATIGUE)
	local newEnergy = md['AndroidTraitData']["NewEnergy"] or 0
	if newEnergy ~= 0 then
		local combined = math.max(0, math.min(1.0, energy + newEnergy))
		if combined >= 0.999 then combined = 1.0 end
		md['AndroidTraitData']["Energy"] = combined
		
		energy = combined
		local perkType = Perks.Strength
		pl:setPerkLevelDebug(perkType, math.max(0, math.min(10, energy * 10)))
		pl:getXp():setXPToLevel(perkType, pl:getPerkLevel(perkType))
		local fitType = Perks.Fitness
		pl:setPerkLevelDebug(fitType, 10)
		pl:getXp():setXPToLevel(fitType, pl:getPerkLevel(fitType))
		SyncXp(pl)
	end
	if md['AndroidTraitData']["NewEnergy"] > 0 then
		stats:set(CharacterStat.ENDURANCE, energy)
	end
	md['AndroidTraitData']["NewEnergy"] = 0
	if drunk > 0 then
		stats:set(CharacterStat.INTOXICATION, 0)
	end
	if hunger > 0 then
		stats:set(CharacterStat.HUNGER, 0)
	end
	if thirst > 0 then
		stats:set(CharacterStat.THIRST, 0)
	end
	if fatigue > 0 then
		stats:set(CharacterStat.FATIGUE, 0)
	end
	AndroidTrait.doAutoOff(pl)
end
Events.OnPlayerUpdate.Remove(AndroidTrait.energyHandler)
Events.OnPlayerUpdate.Add(AndroidTrait.energyHandler)

function AndroidTrait.doAutoOff(pl)
	if not pl then pl = getPlayer() end
	if not pl or not AndroidTrait.hasTrait(pl) then
		return
	end
	local energy = pl:getModData()['AndroidTraitData']["Energy"]
	if energy <= 0 then
		if pl:isWearingNightVisionGoggles() then
			pl:setWearingNightVisionGoggles(false)
		end
	end
end

function AndroidTrait.doAnim(int)
	local pl = getPlayer()
	local act = {
		[1]="WipeLeftArm",
		[2]="WipeArmR",
		[3]="WipeArmL",
		[4]="PullAtColar",
		[5]="WipeBrow",
		[6]="WipeHead",
		[7]="WipeLegL",
		[8]="WipeLegR",
		[9]="WipeTorso1",
	}
	local doAct = act[int] or "WipeLeftArm"
	pl:setVariable("Ext", doAct);
	pl:reportEvent("EventDoExt")
end

function AndroidTrait.isUsingComponent()
	local pl = getPlayer()
	return pl:isWearingNightVisionGoggles()
end

