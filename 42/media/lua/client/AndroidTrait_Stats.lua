function AndroidTrait.getEnergyDrainRate()
	local EnergyDrainRate = SandboxVars.AndroidTrait.EnergyDrainRate or 0.004
	if AndroidTrait.isUsingComponent() then
		EnergyDrainRate = EnergyDrainRate * 1.5
	end
	return EnergyDrainRate
end

function AndroidTrait.energyDrain()
	local pl = getPlayer()
	if not pl or not AndroidTrait.hasTrait(pl) then
		return
	end
	local EnergyDrainRate = AndroidTrait.getEnergyDrainRate()
	local md = pl:getModData()['AndroidTraitData']
	local energy = md["Energy"]
	local newEnergy = math.max(0, energy - EnergyDrainRate)
	md["Energy"] = newEnergy
	local bLvl = "Battery: "..tostring(AndroidTrait.getEnergyPercent()).."%"
	local perkType = Perks.Strength
	pl:setPerkLevelDebug(perkType, math.max(0, math.min(10, newEnergy * 10)))
	pl:getXp():setXPToLevel(perkType, pl:getPerkLevel(perkType))
	SyncXp(pl)
	if newEnergy <= 0.2 then
		local sq = pl:getSquare();
		if isClient() and sq then
			getSoundManager():PlayWorldSound('Android_LowBatt', sq, 0, 5, 5, false);
		else
			getSoundManager():playUISound("Android_LowBatt")
		end
		addSound(pl, pl:getX(), pl:getY(), pl:getZ(), 20, 20);
		getWorld():setDrawWorld(false)
		timer:Simple(5, function()
			getWorld():setDrawWorld(true)
		end)
	end
	if newEnergy <= 0 then
		bLvl = "RECHARGE NOW"
		pl:getBodyDamage():ReduceGeneralHealth(ZombRand(0.5, 3))
	end
	if newEnergy <= 0.2 then
		HaloTextHelper.addTextWithArrow(pl, tostring(bLvl), false, 255,0,0)
	end
end
Events.EveryHours.Remove(AndroidTrait.energyDrain)
Events.EveryHours.Add(AndroidTrait.energyDrain)

function AndroidTrait.initVar()
	local pl = getPlayer()
	if pl and AndroidTrait.hasTrait(pl) then
		pl:setVariable('isAndroid', 'true');
		pl:setMaxWeightBase(123);
	else
		pl:setMaxWeightBase(8);
	end
end
Events.OnCreatePlayer.Remove(AndroidTrait.initVar)
Events.OnCreatePlayer.Add(AndroidTrait.initVar)

function AndroidTrait.initTrait()
    local RecalCD = SandboxVars.AndroidTrait.RecalCD
    local pl = getPlayer()
    if not pl or not AndroidTrait.hasTrait(pl) then return end
    local data = pl:getModData()['AndroidTraitData'] or {}
    if not data.Energy then
        data.Energy = 1
    end
    if not data.NewEnergy then
        data.NewEnergy = 0
    end
    if not data.CD then
        data.CD = RecalCD
    end
    pl:getModData()['AndroidTraitData'] = data
    AndroidTrait.doAutoOff(pl)
end
Events.OnCreatePlayer.Remove(AndroidTrait.initTrait)
Events.OnCreatePlayer.Add(AndroidTrait.initTrait)
